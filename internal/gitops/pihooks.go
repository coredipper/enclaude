package gitops

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// PiHookMarker identifies enclaude-managed pi extensions. Detection is a
// simple substring match so we never have to parse TypeScript.
const PiHookMarker = "// enclaude-managed"

// piExtensionFileName is the generated extension installed into the agent dir.
const piExtensionFileName = "enclaude.ts"

// PiExtensionPath returns the path of the enclaude pi extension for an agent dir.
func PiExtensionPath(agentDir string) string {
	return filepath.Join(agentDir, "extensions", piExtensionFileName)
}

// piExtensionTemplate is a pi extension that drives enclaude's session
// lifecycle hooks. It resolves the enclaude binary at runtime so the file can
// be safely synced between machines with different install paths.
const piExtensionTemplate = `// enclaude-managed
//
// Auto-generated by "enclaude hooks install --source pi". Do not edit by hand;
// remove with "enclaude hooks remove --source pi".
//
// This extension seals pi's agent directory on session start/shutdown by
// invoking the enclaude hook handler.
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const ENCLAUDE_ARGS: string[] = {{ARGS}};

function enclaudeCommand(): string {
	const candidates = [
		process.env.ENCLAUDE_BIN,
		join(homedir(), ".local", "bin", "enclaude"),
		join(homedir(), "go", "bin", "enclaude"),
		"/opt/homebrew/bin/enclaude",
		"/usr/local/bin/enclaude",
	];
	for (const candidate of candidates) {
		if (candidate && existsSync(candidate)) {
			return candidate;
		}
	}
	return "enclaude";
}

async function runEnclaude(pi: ExtensionAPI, action: string, timeout: number): Promise<void> {
	try {
		await pi.exec(enclaudeCommand(), [...ENCLAUDE_ARGS, "hook-handler", action], { timeout });
	} catch {
		// Never let a sync failure block pi.
	}
}

export default function (pi: ExtensionAPI) {
	pi.on("session_start", async () => {
		await runEnclaude(pi, "session-start", 30_000);
	});
	pi.on("session_shutdown", async () => {
		await runEnclaude(pi, "session-end", 60_000);
	});
}
`

// InstallPiHooks writes the enclaude pi extension into agentDir, preserving
// any other extensions. The generated extension pins the source profile and
// seal dir so the hook handler operates on the right store regardless of the
// environment pi was launched from.
func InstallPiHooks(agentDir, sealDir string) error {
	extDir := filepath.Join(agentDir, "extensions")
	if err := os.MkdirAll(extDir, 0755); err != nil {
		return fmt.Errorf("creating extensions directory: %w", err)
	}
	path := PiExtensionPath(agentDir)

	// Never clobber an extension we did not write.
	if existing, err := os.ReadFile(path); err == nil {
		if !strings.Contains(string(existing), PiHookMarker) {
			return fmt.Errorf("refusing to overwrite %s: not an enclaude-managed extension", path)
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("reading existing extension: %w", err)
	}

	args, err := json.Marshal([]string{"--source", "pi", "--seal-dir", sealDir, "--source-dir", agentDir})
	if err != nil {
		return fmt.Errorf("encoding extension args: %w", err)
	}
	src := strings.Replace(piExtensionTemplate, "{{ARGS}}", string(args), 1)
	if err := os.WriteFile(path, []byte(src), 0644); err != nil {
		return fmt.Errorf("writing pi extension: %w", err)
	}
	return nil
}

// RemovePiHooks removes the enclaude pi extension if it is managed by us.
func RemovePiHooks(agentDir string) error {
	path := PiExtensionPath(agentDir)
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("reading pi extension: %w", err)
	}
	if !strings.Contains(string(data), PiHookMarker) {
		return fmt.Errorf("refusing to remove %s: not an enclaude-managed extension", path)
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("removing pi extension: %w", err)
	}
	return nil
}

// PiHooksInstalled reports whether the enclaude pi extension is installed.
func PiHooksInstalled(agentDir string) bool {
	data, err := os.ReadFile(PiExtensionPath(agentDir))
	if err != nil {
		return false
	}
	return strings.Contains(string(data), PiHookMarker)
}
